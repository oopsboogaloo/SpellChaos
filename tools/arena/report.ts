/** Usage: tsx tools/arena/report.ts <out-dir> <results.jsonl>... — writes report.md and matrix.csv. */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { roster, type FightResult, type Side } from './fight.js';

const [outDir, ...files] = process.argv.slice(2);
mkdirSync(outDir!, { recursive: true });
const fights: FightResult[] = [],
  errors: string[] = [];
for (const f of files)
  for (const line of readFileSync(f, 'utf8').split('\n').filter(Boolean)) {
    const r = JSON.parse(line);
    if (r.error) errors.push(`${r.a} vs ${r.b}: ${r.error}`);
    else fights.push(r);
  }
const list = roster(),
  name = new Map(list.map(f => [f.key, f.species]));
type Totals = Side & { fights: number; wins: number; losses: number; draws: number; turns: number };
const totals = new Map<string, Totals>(
  list.map(f => [
    f.key,
    {
      fights: 0,
      wins: 0,
      losses: 0,
      draws: 0,
      turns: 0,
      attacks: 0,
      hits: 0,
      crits: 0,
      dealt: 0,
      taken: 0,
      hpLeft: 0,
      maxHp: 0,
    },
  ]),
);
const head = new Map<string, { w: number; n: number }>(); // "x|y" → x's record against y
for (const r of fights)
  for (const [me, them, side, won] of [
    [r.a, r.b, r.sides.a, r.winner === 'a'],
    [r.b, r.a, r.sides.b, r.winner === 'b'],
  ] as const) {
    const t = totals.get(me)!;
    t.fights++;
    t.turns += r.turns;
    if (r.winner === 'draw') t.draws++;
    else if (won) t.wins++;
    else t.losses++;
    for (const k of ['attacks', 'hits', 'crits', 'dealt', 'taken'] as const) t[k] += side[k];
    const h = head.get(`${me}|${them}`) ?? { w: 0, n: 0 };
    h.n++;
    // A draw counts as half a win.
    h.w += r.winner === 'draw' ? 0.5 : won ? 1 : 0;
    head.set(`${me}|${them}`, h);
  }
const pct = (a: number, b: number) => (b ? `${Math.round((100 * a) / b)}%` : '—');
const num = (a: number, b: number, d = 1) => (b ? (a / b).toFixed(d) : '—');
const score = (t: Totals) => (t.wins + t.draws / 2) / Math.max(1, t.fights);
const rows = list.map(f => ({ f, t: totals.get(f.key)! }));
const line = ({ f, t }: (typeof rows)[number]) =>
  `| ${f.species} | ${f.key.replace(':', ' ')} | ${pct(t.wins + t.draws / 2, t.fights)} | ${t.wins}/${t.losses}/${t.draws} | ${pct(t.hits, t.attacks)} | ${num(t.attacks, t.fights)} | ${num(t.dealt, t.hits)} | ${num(t.dealt, t.fights)} | ${num(t.taken, t.fights)} |`;
const header =
  '| Creature | Spell & level | Score | W/L/D | Hit rate | Attacks/fight | Dmg per hit | Dmg dealt/fight | Dmg taken/fight |\n|---|---|---|---|---|---|---|---|---|';

// Within each family a higher level should beat a lower one; list where it does not.
const inversions: string[] = [];
for (const hi of list)
  for (const lo of list)
    if (hi.spell === lo.spell && hi.level > lo.level) {
      const h = head.get(`${hi.key}|${lo.key}`);
      if (h && h.w / h.n < 0.5)
        inversions.push(`| ${hi.species} (L${hi.level}) | ${lo.species} (L${lo.level}) | ${pct(h.w, h.n)} |`);
    }
// Biggest upsets: a lower-level creature beating a higher-level one from any family most of the time.
const upsets: { text: string; gap: number }[] = [];
for (const x of list)
  for (const y of list)
    if (x.level < y.level) {
      const h = head.get(`${x.key}|${y.key}`);
      if (h && h.w / h.n >= 0.75)
        upsets.push({
          text: `| ${x.species} (L${x.level}) | ${y.species} (L${y.level}) | ${pct(h.w, h.n)} |`,
          gap: y.level - x.level,
        });
    }
upsets.sort((a, b) => b.gap - a.gap);

const perPair = fights.length / Math.max(1, (list.length * (list.length - 1)) / 2);
const md = `# Arena: one-on-one creature fights

Generated by \`tools/arena\` on ${new Date().toISOString().slice(0, 10)}. ${fights.length} fights: every pair of the ${list.length} currently summonable creatures, about ${Math.round(perPair)} fights per pair, with each creature starting on the left in half of them.

**Setup.** Both creatures are bound summons on an open 30 × 30 board, centres 10 hexes apart, no walls or terrain, no wizards. The game's own AI (standard difficulty) plans both sides every turn. A creature loses when it is reduced to 0 HP or below (incapacitated or dead). Fights stop after 40 turns and count as draws.

**Columns.** *Score* is wins plus half of draws, over all fights. *Hit rate* counts attack rolls (each shot or swing). *Dmg per hit* is all damage the creature dealt to its opponent (attacks, powers, spells and retaliation) divided by its hits, so it runs high for creatures whose damage does not come from attacks. Exact damage is visible here because this is a test harness, not a player's view.

**Caveats.** One-on-one on open ground favours ranged attackers and long reach, and ignores what creatures are for in a real game (screening, controlling, supporting a wizard). The AI is not perfect: some creatures may look weak because the AI uses them badly. Treat this as a first look, not a balance verdict.
${
  errors.length
    ? `\n**Errors.** ${errors.length} fights crashed and are not counted:\n\n${errors
        .slice(0, 20)
        .map(e => `- ${e}`)
        .join('\n')}\n`
    : ''
}
## Ranking

${header}
${[...rows]
  .sort((a, b) => score(b.t) - score(a.t))
  .map(line)
  .join('\n')}

## By spell and level

${header}
${rows.map(line).join('\n')}

## Level inversions

A higher-level creature of the same spell that wins less than half its fights against a lower level one.

${inversions.length ? `| Higher level | Lower level | Higher's score |\n|---|---|---|\n${inversions.join('\n')}` : 'None.'}

## Biggest upsets

A lower-level creature (any spell) that wins at least three quarters of fights against a higher-level one, largest level gap first.

${
  upsets.length
    ? `| Lower level | Higher level | Lower's score |\n|---|---|---|\n${upsets
        .slice(0, 40)
        .map(u => u.text)
        .join('\n')}${upsets.length > 40 ? `\n\n…and ${upsets.length - 40} more in matrix.csv.` : ''}`
    : 'None.'
}

## Full matrix

\`matrix.csv\` has the score of each row creature against each column creature.
`;
writeFileSync(`${outDir}/report.md`, md);
const csv = [
  ['', ...list.map(f => `${name.get(f.key)} (${f.key})`)].join(','),
  ...list.map(x =>
    [
      `${x.species} (${x.key})`,
      ...list.map(y => {
        const h = head.get(`${x.key}|${y.key}`);
        return h ? (h.w / h.n).toFixed(2) : '';
      }),
    ].join(','),
  ),
].join('\n');
writeFileSync(`${outDir}/matrix.csv`, csv + '\n');
console.log(`${fights.length} fights, ${errors.length} errors → ${outDir}`);
